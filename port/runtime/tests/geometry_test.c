#include "btga_geometry.h"

#include <assert.h>

static bool count_triangle(const BtgaVertex vertices[3], void *context) {
    unsigned int *count = context;
    assert(vertices[0].x == 1 && vertices[1].y == 1 && vertices[2].z == 1);
    (*count)++;
    return true;
}

int btga_geometry_tests(void) {
    uint8_t chunk[72] = {
        0x01, 0x00, 0x30, 0x06, 0x00, 0x00, 0x00, 0x18,
        0x05, 0x00, 0x02, 0x04, 0x00, 0x00, 0x00, 0x00,
        0xDF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x7F, 0x00, 0x00, 0xFF,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x7F, 0x00, 0xFF,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x7F, 0xFF,
    };
    BtgaGeometrySummary summary;
    unsigned int visits = 0;
    assert(btga_geometry_visit(chunk, sizeof(chunk), count_triangle, &visits, &summary));
    assert(visits == 1 && summary.vertex_load_count == 1 && summary.triangle_count == 1);
    chunk[16] = 0;
    assert(!btga_geometry_visit(chunk, sizeof(chunk), NULL, NULL, &summary));
    return 0;
}
